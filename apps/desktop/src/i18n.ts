export const messages: Record<Lang, Dict> = { zh, en };

export type MessageKey = keyof typeof zh;

/** Translate a key, interpolating `{name}` placeholders. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = messages[lang] ?? messages.zh;
  let text = table[key] ?? messages.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

/** Human label for a backend enum value, falling back to the raw value. */
export function enumLabel(lang: Lang, group: string, value: string): string {
  const key = `${group}.${value}`;
  const table = messages[lang] ?? messages.zh;
  return table[key] ?? messages.zh[key] ?? value.replace(/_/g, ' ');
}

/** Archetype label, mapping the backend's snake_case id. */
export function archetypeLabel(lang: Lang, archetype: string): string {
  return enumLabel(lang, 'arch', archetype);
}

/** Status label, mapping the backend's snake_case id. */
export function statusLabel(lang: Lang, status: string): string {
  return enumLabel(lang, 'status', status);
}

/** Thinking-level label. */
export function thinkLabel(lang: Lang, level: string): string {
  return enumLabel(lang, 'think', level || 'auto');
}
